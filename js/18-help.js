function vHelp(){
  const open = UI.helpSec || "start";
  return `<div class="guide">${HELP.map(s => `<details class="panel" id="help-${s.k}"${s.k === open ? " open" : ""}><summary>${s.t}</summary><div class="gbody">${s.b()}</div></details>`).join("")}</div>`;
}
/* before there is a line, the guide takes the place of the setup screen until "חזרה" */
function vHelpFirst(){
  return `<div class="row" style="margin-bottom:6px"><button class="btn ghost sm" data-a="helpBack">› חזרה</button><h2 class="subt">מדריך שימוש</h2></div>` + vHelp();
}
Object.assign(ACT, {
  helpOpen: v => {
    closeSheet(); UI.helpSec = v || null;
    if (cfg()){ UI.tab = "more"; UI.more = "help"; saveUI(); } else UI.helpFirst = true;
    render();
    const el = v && document.getElementById("help-" + v);
    if (el) el.scrollIntoView({ block:"start" }); else window.scrollTo(0, 0);
  },
  helpBack: () => { UI.helpFirst = false; render(); window.scrollTo(0, 0); },
  helpCopyLink: () => copyText(appLink()),
  startNew: () => { const w = document.getElementById("wizard"); if (w) w.scrollIntoView({ behavior:"smooth", block:"start" }); },
  startJoin: () => joinSheet(),
});
